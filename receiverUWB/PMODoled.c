#define OLED_W      128
#define OLED_PAGES  4
static u8 fb[OLED_PAGES][OLED_W];  /* fb[page][col] */
 
static void spi_send(u8 is_data, u8 byte)
{
    /* set D/C flag */
    if (is_data) flags_state |=  0x01;
    else         flags_state &= ~0x01;
    XGpio_DiscreteWrite(&GpioCtrl, 2, flags_state);
    /* put byte on data bus and pulse START */
    XGpio_DiscreteWrite(&GpioData, 1, (u32)byte);
    flags_state |= 0x02;
    XGpio_DiscreteWrite(&GpioCtrl, 2, flags_state);
    /* wait for VHDL to signal done */
    while ((XGpio_DiscreteRead(&GpioData, 2) & 0x01) == 0);
    /* clear START */
    flags_state &= ~0x02;
    XGpio_DiscreteWrite(&GpioCtrl, 2, flags_state);
}

#define oled_cmd(x)   spi_send(0, (x))
#define oled_data(x)  spi_send(1, (x))

static void oled_power_on(void)
{
    /* VDD on, VBAT off, RESET asserted */
    ctrl_state = 0x06;
    XGpio_DiscreteWrite(&GpioCtrl, 1, ctrl_state);
    usleep(1000);
    /* release RESET */
    ctrl_state |= 0x01;
    XGpio_DiscreteWrite(&GpioCtrl, 1, ctrl_state);
    usleep(1000);
}
 
static void oled_init(void)
{
    oled_cmd(0xAE);             /* display off                      */
    oled_cmd(0xD5); oled_cmd(0x80); /* clock: default osc, div=1   */
    oled_cmd(0xA8); oled_cmd(0x1F); /* mux ratio = 31 (32 rows)    */
    oled_cmd(0xD3); oled_cmd(0x00); /* display offset = 0          */
    oled_cmd(0x40);             /* display start line = 0           */
    oled_cmd(0x8D); oled_cmd(0x14); /* charge pump enable          */
    oled_cmd(0x20); oled_cmd(0x00); /* horizontal addressing mode  */
    oled_cmd(0xA1);             /* segment remap (mirror X)         */
    oled_cmd(0xC8);             /* COM scan flip (mirror Y)         */
    oled_cmd(0xDA); oled_cmd(0x02); /* COM pins: sequential, 128x32*/
    oled_cmd(0x81); oled_cmd(0x8F); /* contrast                    */
    oled_cmd(0xD9); oled_cmd(0xF1); /* pre-charge period           */
    oled_cmd(0xDB); oled_cmd(0x40); /* VCOMH deselect level        */
    oled_cmd(0xA4);             /* output follows RAM              */
    oled_cmd(0xA6);             /* normal display (not inverted)   */
    /* enable VBAT and wait for charge pump */
    ctrl_state &= ~0x04;
    XGpio_DiscreteWrite(&GpioCtrl, 1, ctrl_state);
    usleep(100000);
    oled_cmd(0xAF);             /* display on                      */
    usleep(100000);
}
 
static void oled_flush(void)
{
    oled_cmd(0x22); oled_cmd(0x00); oled_cmd(0x03); /* pages 0-3   */
    oled_cmd(0x21); oled_cmd(0x00); oled_cmd(0x7F); /* cols 0-127  */
 
    for (int page = 0; page < OLED_PAGES; page++)
        for (int col = 0; col < OLED_W; col++)
            oled_data(fb[page][col]);
}

static void oled_clear(void)
{
    for (int p = 0; p < OLED_PAGES; p++)
        for (int c = 0; c < OLED_W; c++)
            fb[p][c] = 0x00;
}
 
static int oled_draw_char(int x, int page, char c)
{
    if (x + 5 > OLED_W) return x;          /* no room */
    if (c < 32 || c > 126) c = '?';
    const u8 *glyph = font5x7[c - 32];
    for (int col = 0; col < 5; col++)
        fb[page][x + col] = glyph[col];
    fb[page][x + 5] = 0x00;                /* 1px gap */
    return x + 6;
}

void oled_print(int x, int page, const char *str)
{
    for (; *str != '\0'; str++) {
        if (x + 6 > OLED_W) {              /* wrap to next page   */
            x = 0;
            page++;
        }
        if (page >= OLED_PAGES) break;     /* off the bottom      */
        x = oled_draw_char(x, page, *str);
    }
}
 
void gpio_init()
{
    XGpio_Initialize(&GpioCtrl, XPAR_XGPIO_0_BASEADDR);
    XGpio_Initialize(&GpioData, XPAR_XGPIO_1_BASEADDR);
    XGpio_SetDataDirection(&GpioCtrl, 1, 0x00);  /* all outputs */
    XGpio_SetDataDirection(&GpioCtrl, 2, 0x00);
    XGpio_SetDataDirection(&GpioData, 1, 0x00);
    XGpio_SetDataDirection(&GpioData, 2, 0xFF);  /* all inputs  */
    XGpio_DiscreteWrite(&GpioCtrl, 1, 0x00);
    XGpio_DiscreteWrite(&GpioCtrl, 2, 0x00);
}

void oled_handler(char str[38])
{
    char part1[9];
    char part2[9];
    char part3[7];
    char part4[9];
    char part5[9];
    sscanf(str, "%8s %8s %6s %8s %8s",
           part1, part2, part3, part4, part5);

    oled_clear();

    char line0[20];
    sprintf(line0, "%s %s", part1, part2);
    oled_print(0, 0, line0);
    
    oled_print(0, 1, part3);

    char line2[20];
    sprintf(line2, "%s %s", part4, part5);
    oled_print(0, 2, line2);

    oled_flush();
    cleanup_platform();
}

int main(void)
{
    init_platform();
    gpio_init();
    
    oled_power_on();
    oled_init();
 
    oled_handler("abcdef012345678900112233445566778899ab");

    return 0;
}
